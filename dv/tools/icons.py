"""Smaller list icons at Tamzen's scale: 8x9 ink at column 1, row 1 of the 10x12 cell."""
ICONS = {
    0xC0: ["........", ".###....", "#...#...", "########", "#......#", "#......#", "#......#", "#......#", "########"],   # folder
    0xC1: ["........", "########", "#......#", "#.####.#", "#.####.#", "#.####.#", "#......#", "#......#", "#######."],   # gb cart (notched corner)
    0xC2: ["........", ".######.", "#......#", "#.####.#", "#.#..#.#", "#.####.#", "#......#", "#......#", ".######."],   # gbc cart (rounded)
    0xC3: ["........", "########", "#......#", "#..##..#", "#.#..#.#", "#...#..#", "#......#", "#...#..#", "########"],   # unknown "?"
    0x7F: ["........", "...##...", "...##...", "########", ".######.", "..####..", ".######.", ".##..##.", "##....##"],   # star (glyph $7F)
    0xC4: ["........", "#####...", "#...##..", "#...#.#.", "#...####", "#......#", "#......#", "#......#", "########"],   # .sav page
}

def cell(code):
    """10x12 cell rows (lists of 0/1): icon ink at column 1.., row 1.. (first art row is blank)."""
    rows = [[0] * 10 for _ in range(12)]
    for r, line in enumerate(ICONS[code]):
        for c, ch in enumerate(line):
            if ch == "#":
                rows[1 + r][1 + c] = 1
    return rows
